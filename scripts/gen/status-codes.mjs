#!/usr/bin/env node
// 契约生成器：contracts/status-codes.yaml → Go 常量 + TS 常量 + 索引文档。
// 用法：
//   node scripts/gen/status-codes.mjs            # 生成并写入目标文件（自动 gofmt）
//   node scripts/gen/status-codes.mjs --check    # 生成物一致性检查（过期则 exit 1）
// 生成物（入库，禁止手改）：
//   internal/kernel/errorx/codes_gen.go
//   admin/src/constants/status-codes.ts
//   docs/rules/status-codes-index.md
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseStatusCodes } from "../ci/lib.mjs";

const ROOT = path.dirname(path.dirname(path.dirname(fileURLToPath(import.meta.url))));
const checkMode = process.argv.includes("--check");

// ---------- 解析契约 ----------
const text = fs.readFileSync(path.join(ROOT, "contracts", "status-codes.yaml"), "utf8");
const { ranges, codes, success } = parseStatusCodes(text);
codes.sort((a, b) => Number(a.code) - Number(b.code));

const pad = (arr, key) => Math.max(...arr.map((o) => String(o[key]).length));
const nameW = pad(codes, "name") + 1;

// ---------- Go ----------
const consts = codes
  .map((c) =>
    c.deprecated
      ? `\t// Deprecated: ${c.since} 起弃用，禁止新用（docs/rules/status-codes.md §9）\n\t${String(c.name).padEnd(nameW)}= "${c.code}"`
      : `\t${String(c.name).padEnd(nameW)}= "${c.code}"`,
  )
  .join("\n");
const goHTTP = codes.map((c) => `\t"${c.code}": ${c.http},`).join("\n");
const goKey = codes.map((c) => `\t"${c.code}": "${c.message_key}",`).join("\n");
const goRetry = codes.map((c) => `\t"${c.code}": ${c.retryable},`).join("\n");
const goSince = codes.map((c) => `\t"${c.code}": "${c.since}",`).join("\n");
const goDep = codes.map((c) => `\t"${c.code}": ${c.deprecated},`).join("\n");
const goSrc = `// Code generated by scripts/gen/status-codes.mjs from contracts/status-codes.yaml; DO NOT EDIT.

package errorx

// 5 位状态码常量（成功码 ${success}）。
// 新增/修改请走 contracts/status-codes.yaml + 重新生成（go generate ./...），
// 禁止在业务代码手写数字（docs/rules/status-codes.md）。
const (
${consts}
)

// codeHTTP 状态码 → HTTP 传输语义（业务语义看常量值本身）。
var codeHTTP = map[string]int{
${goHTTP}
}

// codeMessageKey 状态码 → i18n 文案键（对外信封字段，docs/rules/api-style.md §4）。
var codeMessageKey = map[string]string{
${goKey}
}

// codeRetryable 状态码 → 是否可重试（reliability.md：只重试幂等）。
var codeRetryable = map[string]bool{
${goRetry}
}

// codeSince 状态码 → 登记版本（§9）。
var codeSince = map[string]string{
${goSince}
}

// codeDeprecated 状态码 → 是否已弃用（弃用码禁止新用）。
var codeDeprecated = map[string]bool{
${goDep}
}
`;

// ---------- TS ----------
const tsEntries = codes.map((c) => `  ${c.name}: "${c.code}",`).join("\n");
const tsHTTP = codes.map((c) => `  "${c.code}": ${c.http},`).join("\n");
const tsKey = codes.map((c) => `  "${c.code}": "${c.message_key}",`).join("\n");
const tsSince = codes.map((c) => `  "${c.code}": "${c.since}",`).join("\n");
const tsSrc = `// Code generated by scripts/gen/status-codes.mjs from contracts/status-codes.yaml. DO NOT EDIT.
// 5 位状态码常量（成功码 ${success}）；文档见 docs/rules/status-codes.md 与 api-style.md §4。

export const StatusCode = {
${tsEntries}
} as const;

export type StatusCode = (typeof StatusCode)[keyof typeof StatusCode];

const HTTP_MAP: Record<string, number> = {
${tsHTTP}
};

const MESSAGE_KEY_MAP: Record<string, string> = {
${tsKey}
};

const SINCE_MAP: Record<string, string> = {
${tsSince}
};

const RETRYABLE_SET = new Set<string>(${JSON.stringify(codes.filter((c) => c.retryable === true).map((c) => c.code))});

const DEPRECATED_SET = new Set<string>(${JSON.stringify(codes.filter((c) => c.deprecated === true).map((c) => c.code))});

/** 是否成功码（${success}） */
export function isSuccess(code: string): boolean {
  return code === "${success}";
}

/** 状态码 → HTTP 传输语义 */
export function httpStatus(code: string): number | undefined {
  return HTTP_MAP[code];
}

/** 状态码 → i18n 文案键（对外信封 message_key 字段） */
export function messageKey(code: string): string | undefined {
  return MESSAGE_KEY_MAP[code];
}

/** 该码是否可重试 */
export function retryable(code: string): boolean {
  return RETRYABLE_SET.has(code);
}

/** 该码是否已弃用（禁止新用） */
export function deprecated(code: string): boolean {
  return DEPRECATED_SET.has(code);
}

/** 该码登记版本 */
export function since(code: string): string | undefined {
  return SINCE_MAP[code];
}
`;

// ---------- 索引文档 ----------
const idxRows = codes
  .map((c) => `| ${c.code} | ${c.name} | ${c.surface} | ${c.domain} | ${c.http} | ${c.retryable} | ${c.since} | ${c.deprecated} | ${c.message_key} | ${c.owner} |`)
  .join("\n");
const idxRanges = ranges.map((r) => `| ${r.start}-${r.end} | ${r.owner} | ${r.purpose} |`).join("\n");
const idxSrc = `<!-- Code generated by scripts/gen/status-codes.mjs from contracts/status-codes.yaml. DO NOT EDIT. -->

# 状态码索引（自动生成）

单一事实源：[contracts/status-codes.yaml](../../contracts/status-codes.yaml)；规则：[status-codes.md](status-codes.md)。

## 范围段

| 范围 | owner | 用途 |
|------|-------|------|
${idxRanges}

## 已登记码（${codes.length} 个，成功码 ${success}）

| code | 名称 | surface | domain | http | retryable | since | deprecated | message_key | owner |
|------|------|---------|--------|------|-----------|-------|------------|-------------|-------|
${idxRows}
`;

// ---------- 写盘 / 检查 ----------
const targets = [
  { rel: path.join("internal", "kernel", "errorx", "codes_gen.go"), src: goSrc, gofmt: true },
  { rel: path.join("admin", "src", "constants", "status-codes.ts"), src: tsSrc },
  { rel: path.join("docs", "rules", "status-codes-index.md"), src: idxSrc },
];

function gofmt(p) {
  try {
    execFileSync("gofmt", ["-w", p], { stdio: "ignore" });
  } catch (e) {
    console.error(`[gen] gofmt 失败（CI gofmt -l 兜底）: ${p}`);
  }
}

const stale = [];
for (const t of targets) {
  const abs = path.join(ROOT, t.rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  if (checkMode) {
    if (!fs.existsSync(abs)) { stale.push(`${t.rel}（缺失）`); continue; }
    const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "na-gen-")), path.basename(abs));
    fs.writeFileSync(tmp, t.src);
    if (t.gofmt) gofmt(tmp);
    if (fs.readFileSync(abs, "utf8") !== fs.readFileSync(tmp, "utf8")) stale.push(t.rel);
    fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
  } else {
    fs.writeFileSync(abs, t.src);
    if (t.gofmt) gofmt(abs);
    console.log(`[gen] ${path.relative(ROOT, abs).replaceAll("\\", "/")}`);
  }
}

if (checkMode) {
  if (stale.length > 0) {
    for (const s of stale) console.log(`[FAIL] generated: ${s} 过期 —— 重新生成：node scripts/gen/status-codes.mjs`);
    process.exit(1);
  }
  console.log(`[PASS] generated（${targets.length} 个生成物与契约一致）`);
}
